    L.append(f"Crashes: {hw['crash']}. Timeouts: {hw['timeout']}. Hardware-confirmed instructions per decoded class: " +
             ", ".join(f"{m['title']} {m['numerator']}/{m['denominator']}"
                       for m in inv["measurements"]["isa_coverage"]["classes"].values()) + ".")
