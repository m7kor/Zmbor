    L.append("| area | programs exact | output lines matching |")
    L.append("|---|---|---|")
    for area, v in hw["by_area"].items():
        L.append(f"| `{area}` | {v['programs_pass']} / {v['programs']} | {v['lines_match']} / {v['lines']} "
                 f"({pct(v['lines_match'], v['lines'])}) |")
    L.append(f"| **all** | **{hw['programs_pass']} / {hw['programs']}** | **{hw['lines_match']} / {hw['lines']}** "
             f"(**{pct(hw['lines_match'], hw['lines'])}**) |")
