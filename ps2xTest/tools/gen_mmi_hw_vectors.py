#!/usr/bin/env python3
"""Generate ps2xTest/src/ps2_mmi_hw_vectors.inc from ps2autotests' tests/cpu/ee_simd/muldiv.expected.

The expected file holds results printed by a real PS2 (https://github.com/unknownbrackets/ps2autotests, ISC
license). Inputs are reconstructed from muldiv.cpp's TEST_RRRHL_FUNC case list, which is identical for every
operation: 13 SET_U32 cases with rd = 0x1337, then 19 SET_M cases with rd = C_GARBAGE1, all starting from C_HILO.

Usage: gen_mmi_hw_vectors.py <muldiv.expected> <out.inc>
"""
import re
import sys

OPS = ('phmadh', 'phmsbh', 'pmaddh', 'pmsubh', 'pmulth', 'pmaddw', 'pmadduw', 'pmsubw', 'pmultw', 'pmultuw')

CONST = {  # tests/cpu/ee_simd/shared.h and muldiv.cpp
    'C_ZERO': [0, 0, 0, 0], 'C_ONE': [1, 0, 0, 0], 'C_NEGONE': [0xFFFFFFFF] * 4,
    'C_S16_MAX': [0x7FFF, 0, 0, 0], 'C_S16_MIN': [0xFFFF8000, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF],
    'C_S32_MAX': [0x7FFFFFFF, 0, 0, 0], 'C_S32_MIN': [0x80000000, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF],
    'C_S64_MAX': [0xFFFFFFFF, 0x7FFFFFFF, 0, 0], 'C_S64_MIN': [0, 0x80000000, 0xFFFFFFFF, 0xFFFFFFFF],
    'C_GARBAGE1': [0x1337, 0x1338, 0x1339, 0x133A], 'C_GARBAGE2': [0xDEADBEEF, 0xDEADBEEE, 0xDEADBEED, 0xDEADBEEC],
    'C_TWOTWOTWOTWO': [2, 2, 2, 2], 'C_ONEONEONEONE': [1, 1, 1, 1],
    'C_P_S8_A': [0x80808080, 0xFFFFFFFF, 0x12345678, 0x7F7F7F7F], 'C_P_S8_B': [0x80FF127F, 0xFF807F34, 0x567F80FF, 0x7F78FF80],
    'C_P_S16_A': [0x80008000, 0xFFFFFFFF, 0x12345678, 0x7FFF7FFF], 'C_P_S16_B': [0x8000FFFF, 0x12347FFF, 0xFFFF8000, 0x7FFF5678],
    'C_P_S32_A': [0x80000000, 0xFFFFFFFF, 0x12345678, 0x7FFFFFFF], 'C_P_S32_B': [0xFFFFFFFF, 0x80000000, 0x7FFFFFFF, 0x12345678],
    'C_P_S32_C': [0x80000000, 0xFFFFFFFF, 0x12345678, 0x7FFFFFFF], 'C_P_S32_D': [0x7FFFFFFF, 0x12345678, 0xFFFFFFFF, 0x80000000],
    'C_P_S32_E': [0x00000000, 0x7FFFFFFF, 0xFFFFFFFF, 0x80000000], 'C_P_S32_F': [0xFFFFFFFF, 0x80000000, 0x00000000, 0x7FFFFFFF],
}
III = [(0, 0), (0, 1), (1, 0), (1, 1), (2, 2), (53, 2), (53, 0), (0xFFFFFFFF, 1), (1, 0xFFFFFFFF),
       (0xFFFFFFFF, 0xFFFFFFFF), (0x80000000, 0xFFFFFFFF), (0x80000000, 0), (0x12341234, 0x56785678)]
MMM = [('C_ZERO', 'C_ONE'), ('C_ONE', 'C_ONE'), ('C_ONE', 'C_NEGONE'), ('C_S16_MAX', 'C_S16_MAX'),
       ('C_S16_MIN', 'C_S16_MIN'), ('C_S32_MAX', 'C_S32_MAX'), ('C_S32_MIN', 'C_S32_MIN'), ('C_S64_MAX', 'C_S64_MAX'),
       ('C_S64_MIN', 'C_S64_MIN'), ('C_GARBAGE1', 'C_GARBAGE2'), ('C_TWOTWOTWOTWO', 'C_ONEONEONEONE'),
       ('C_P_S8_A', 'C_P_S8_B'), ('C_P_S16_A', 'C_P_S16_B'), ('C_P_S32_A', 'C_P_S32_B'), ('C_P_S32_B', 'C_P_S32_A'),
       ('C_P_S32_C', 'C_P_S32_D'), ('C_P_S32_D', 'C_P_S32_C'), ('C_P_S32_E', 'C_P_S32_F'), ('C_P_S32_F', 'C_P_S32_E')]


def set_u32(i):
    """lui/ori sign-extends to 64 bits, pcpyld copies the doubleword to both halves."""
    hi = 0xFFFFFFFF if i & 0x80000000 else 0
    return [i, hi, i, hi]


def cases():
    for s, t in III:
        yield set_u32(0x1337), set_u32(s), set_u32(t), f'{s:#x}, {t:#x}'
    for s, t in MMM:
        yield CONST['C_GARBAGE1'], CONST[s], CONST[t], f'{s}, {t}'


LINE = re.compile(r'^\s+(\w+) [^:]+: ([0-9a-f]{8}) ([0-9a-f]{8}) ([0-9a-f]{8}) ([0-9a-f]{8}) '
                  r'H: ([0-9a-f]{16}) ([0-9a-f]{16}) L: ([0-9a-f]{16}) ([0-9a-f]{16})$')


def main():
    text = open(sys.argv[1], encoding='utf-8').read().splitlines()
    rows = {op: [] for op in OPS}
    for line in text:
        m = LINE.match(line)
        if m and m.group(1) in rows:
            rows[m.group(1)].append(m.groups()[1:])
    out = ['// Generated by ps2xTest/tools/gen_mmi_hw_vectors.py from ps2autotests tests/cpu/ee_simd/muldiv.expected',
           '// (results printed by a real PS2; https://github.com/unknownbrackets/ps2autotests, ISC license).',
           '// Columns: op, rd before, rs, rt, rd after, HI, HI1, LO, LO1 (all start from muldiv.cpp C_HILO). Words are',
           '// listed low to high.']
    total = 0
    for op in OPS:
        got = rows[op]
        expected_cases = list(cases())
        if len(got) != len(expected_cases):
            raise SystemExit(f'{op}: {len(got)} result rows, {len(expected_cases)} cases')
        for (rd0, rs, rt, label), r in zip(expected_cases, got):
            rd = [int(r[3], 16), int(r[2], 16), int(r[1], 16), int(r[0], 16)]
            hi, hi1, lo, lo1 = (int(x, 16) for x in r[4:8])
            words = lambda v: '{' + ', '.join(f'0x{w:08X}u' for w in v) + '}'
            out.append(f'{{"{op}", {words(rd0)}, {words(rs)}, {words(rt)}, {words(rd)}, '
                       f'0x{hi:016X}ull, 0x{hi1:016X}ull, 0x{lo:016X}ull, 0x{lo1:016X}ull}}, // {label}')
            total += 1
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'{total} vectors')


if __name__ == '__main__':
    main()
