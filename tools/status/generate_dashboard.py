def load(path=INVENTORY):
    return json.loads(path.read_text(encoding="utf-8"))


def leaves_of(node):
    if "children" in node:
        for c in node["children"]:
            yield from leaves_of(c)
    else:
        yield node


def status_counts(node):
    counts = {s: 0 for s in STATUSES}
    for leaf in leaves_of(node):
        counts[leaf["status"]] += 1
    return counts


def summary(inv):
    out = {"leaves": 0, "by_status": {s: 0 for s in STATUSES}, "sections": {}}
    for sec in inv["sections"]:
        c = status_counts(sec)
        out["sections"][sec["id"]] = {"leaves": sum(c.values()), "by_status": c}
        out["leaves"] += sum(c.values())
        for s in STATUSES:
            out["by_status"][s] += c[s]
    return out


def pct(n, d):
    """One decimal, truncated (never rounded up), so 99.96% is shown as 99.9% and 100.0% only when n == d."""
    if d == 0:
        return None
    v = math.floor(1000 * n / d) / 10
    return f"{v:.1f}%"


# --------------------------------------------------------------------------------------------------------------
# Treemap layout (squarified, deterministic)
# --------------------------------------------------------------------------------------------------------------

def _worst(row, w):
    s = sum(row)
    return max(max(w * w * r / (s * s), (s * s) / (w * w * r)) for r in row)


CELL_ASPECT = 2.4  # target width:height of cells; text labels need wide cells, not squares


def squarify(weights, x, y, w, h, aspect=CELL_ASPECT):
    """Squarified treemap (Bruls et al.) computed in a space compressed horizontally by `aspect`, so the cells it
    makes "square" there come out `aspect` times wider than tall. Returns one (x, y, w, h) per weight, in order."""
    rects = _squarify(weights, 0.0, 0.0, w / aspect, h)
    return [(x + rx * aspect, y + ry, rw * aspect, rh) for rx, ry, rw, rh in rects]


def _squarify(weights, x, y, w, h):
    total = sum(weights)
    if total <= 0:
        return [(x, y, 0, 0) for _ in weights]
    scale = w * h / total
    areas = [wt * scale for wt in weights]
    rects = []
    i = 0
    while i < len(areas):
        short = min(w, h)
        row = [areas[i]]
        j = i + 1
        while j < len(areas) and _worst(row + [areas[j]], short) <= _worst(row, short):
            row.append(areas[j])
            j += 1
        s = sum(row)
        if w >= h:  # lay the row out as a column on the left
            cw = s / h
            yy = y
            for a in row:
                rects.append((x, yy, cw, a / cw))
                yy += a / cw
            x, w = x + cw, w - cw
        else:  # lay the row out as a row on top
            rh = s / w
            xx = x
            for a in row:
                rects.append((xx, y, a / rh, rh))
                xx += a / rh
            y, h = y + rh, h - rh
        i = j
    return rects


# Character advance in em for the dashboard's sans-serif stack, deliberately generous (Segoe UI / Helvetica /
# Arial are all narrower), so a label measured to fit here fits in every browser font of the stack.
_NARROW = set("il.,:;|!'`()[]{}/-ftrjI1 ")
_WIDE = set("mwMW@%&")


def text_width(s, size):
    w = 0.0
    for ch in s:
        if ch in _NARROW:
            w += 0.36
        elif ch in _WIDE:
            w += 0.92
        elif ch.isupper() or ch.isdigit():
            w += 0.68
        else:
            w += 0.58
    return w * size


def wrap(text, size, max_w, max_lines):
    words = text.split()
    lines, cur = [], ""
    for wd in words:
        cand = (cur + " " + wd).strip()
        if text_width(cand, size) <= max_w:
            cur = cand
        else:
            if cur:
                lines.append(cur)
            cur = wd
            if text_width(cur, size) > max_w:
                return None
    if cur:
        lines.append(cur)
    return lines if len(lines) <= max_lines else None


class LayoutError(Exception):
    pass


def fit_label(leaf, w, h):
    """Largest font (11..8 px) at which the name, else the short name, fits the cell without clipping."""
    pad = 4
    labels = [leaf["name"]] + ([leaf["short"]] if leaf.get("short") else [])
    # Readable sizes first (GitHub scales the 1000 px canvas to about 830 px), then 8 px as a last resort.
    attempts = [(lb, sz) for sz in (11, 10, 9) for lb in labels[:1]] + [(lb, sz) for sz in (11, 10, 9) for lb in labels[1:]] \
        + [(lb, 8) for lb in labels]
    for label, size in attempts:
        line_h = size + 2
        max_lines = int((h - 2 * pad) // line_h)
        if max_lines < 1:
            continue
        lines = wrap(label, size, w - 2 * pad, max_lines)
        if lines:
            return size, lines
    raise LayoutError(f"label of {leaf['id']} does not fit a {w:.0f}x{h:.0f} cell: add or shorten 'short'")


