#!/usr/bin/env python3
"""Regenerate docs/community-research/REUSABLE_IMPROVEMENTS.md from research/candidates/*.json."""
import collections
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
records = [r for f in sorted((ROOT / "research" / "candidates").glob("*.json"))
           for r in json.loads(f.read_text(encoding="utf-8"))]
by_id = {r["id"]: r for r in records}


def cell(value, limit=150):
    value = " ".join(str(value or "").split()).replace("|", "\\|")
    return value if len(value) <= limit else value[: limit - 1] + "…"


lines = [
    "# Reusable improvements from community PS2 recompilation projects",
    "",
    "Generated by `tools/research/make_report.py` from `research/candidates/*.json`; edit the records, not this file.",
    "Status meanings: INTEGRATED = built and tested in this repository (commit and tests in the record);",
    "CANDIDATE = source inspection only, nothing built or tested here.",
    "",
    "## Totals",
    "",
    "| Status | Records |",
    "|---|---|",
]
for status, count in sorted(collections.Counter(r["status"] for r in records).items()):
    lines.append(f"| {status} | {count} |")

lines += ["", "## Integrated", "", "| Id | Source | Title | Commit | Tests |", "|---|---|---|---|---|"]
for r in records:
    if r["status"] == "INTEGRATED":
        ev = r.get("evidence", {})
        lines.append(f"| {r['id']} | {cell(r['source'].get('repository'))} | {cell(r['title'])} | "
                     f"{cell(ev.get('integration_commit'))} | {len(ev.get('tests_added', []))} |")

lines += ["", "## Queue: general candidates, priority 1-2", "",
          "Ordered by priority, then risk. The agent's scope judgement is in each record's `scope_evidence`.", "",
          "| Id | Cat | Subsystem | Title | Risk | Upstream equivalent |", "|---|---|---|---|---|---|"]
risk_order = {"low": 0, "medium": 1, "unknown": 2, "high": 3}
queue = [r for r in records if r["status"] == "CANDIDATE" and r["scope"] == "general" and r.get("priority", 5) <= 2]
for r in sorted(queue, key=lambda r: (r.get("priority", 5), risk_order.get(r["risk"], 2), r["id"])):
    lines.append(f"| {r['id']} | {r['category']} | {cell(r['subsystem'], 60)} | {cell(r['title'], 110)} | "
                 f"{r['risk']} | {cell(r.get('upstream_equivalent'), 60)} |")

lines += ["", "## Architecture references", "", "| Id | Source | Title |", "|---|---|---|"]
for r in records:
    if r["status"] == "ARCHITECTURE_REFERENCE":
        lines.append(f"| {r['id']} | {cell(r['source'].get('repository'))} | {cell(r['title'])} |")

lines += ["", "## Rejected or game-specific", "", "| Id | Status | Title | Reason |", "|---|---|---|---|"]
for r in records:
    if r["status"] in {"REJECTED", "GAME_SPECIFIC"}:
        reason = r.get("limitations") or r.get("scope_evidence")
        lines.append(f"| {r['id']} | {r['status']} | {cell(r['title'], 100)} | {cell(reason, 120)} |")

out = ROOT / "docs" / "community-research" / "REUSABLE_IMPROVEMENTS.md"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} ({len(queue)} queued candidates)")
