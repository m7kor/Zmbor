def outputs(inv):
    files = {}
    for sec in inv["sections"]:
        files[ROOT / sec["svg"]] = render_section(inv, sec)
    files[STATUS_README] = render_status_readme(inv)
    top = TOP_README.read_text(encoding="utf-8")
    if README_BEGIN not in top or README_END not in top:
        raise LayoutError("README.md has no status-dashboard block markers")
    head, rest = top.split(README_BEGIN, 1)
    _, tail = rest.split(README_END, 1)
    files[TOP_README] = head + render_readme_block(inv) + tail
    return files


def cmd_generate(check):
    inv = load()
    stale = []
    for path, content in outputs(inv).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.write_text(content, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("stale generated files (run tools/status/generate_dashboard.py): " + ", ".join(stale))
            return 1
        print("generated files are up to date")
        return 0
    print("wrote " + (", ".join(stale) if stale else "nothing (up to date)"))
    return 0


def cmd_measure(autotests):
    inv = load()
    dash = json.loads(HW_DASHBOARD.read_text(encoding="utf-8"))
    inv["measurements"]["hardware_source"]["sha256"] = sha256(HW_DASHBOARD)
    inv["measurements"]["hardware"] = measure_hw(dash)
    inv["measurements"]["isa_coverage"]["classes"] = measure_isa(autotests, dash, decoded_isa())
    INVENTORY.write_text(json.dumps(inv, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print("measurements updated in docs/status/components.json; review and commit the diff")
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true")
    sub = p.add_subparsers(dest="cmd")
    m = sub.add_parser("measure")
    m.add_argument("--autotests", required=True)
    args = p.parse_args(argv)
    if args.cmd == "measure":
        return cmd_measure(args.autotests)
    return cmd_generate(args.check)


if __name__ == "__main__":
    sys.exit(main())
