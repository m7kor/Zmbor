    L.append(f"Every component, its evidence and the method are listed in [docs/status](docs/status/README.md). "
             f"Colours are statuses written by hand and checked against cited evidence; they are not code coverage.")
    L.append("")
    L.append("### Verified hardware results")
    L.append("")
    L.append(f"The [ps2autotests](https://github.com/unknownbrackets/ps2autotests) programs (ISC) print results that were "
             f"captured on a real PS2. Zmbor recompiles each program to native code and compares its output line by line "
             f"with the unmodified `.expected` file (evidence commit `{inv['evidence_commit']}`):")
