def _r(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def _title(leaf):
    parts = [f"{leaf['id']} — {leaf['name']}", f"status: {leaf['status']}"]
    if leaf.get("implemented"):
        parts.append("implemented: " + leaf["implemented"])
    if leaf.get("missing"):
        parts.append("missing: " + leaf["missing"])
    if leaf.get("hw"):
        parts.append("hardware programs: " + ", ".join(leaf["hw"]))
    if leaf.get("hwvec"):
        parts.append("real-PS2 vectors: " + "; ".join(r.split("::")[-1] for r in leaf["hwvec"]))
    if leaf.get("blocker"):
        parts.append("blocker: " + leaf["blocker"])
    return "\n".join(parts)


def render_section(inv, section):
    width = section["layout"]["width"]
    height = section["layout"]["height"]
    hw = inv["measurements"]["hardware"]
    out = []
    a = out.append
    a(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
      f'font-family="{FONT}" role="img" aria-labelledby="t-{section["id"]}">')
    a(f'<title id="t-{section["id"]}">Zmbor — {escape(section["title"])}: component status '
      f'(generated from docs/status/components.json at {inv["evidence_commit"]})</title>')
    a(f'<rect width="{width}" height="{height}" fill="{BG}"/>')
    # header
    a(f'<text x="16" y="30" fill="{TEXT}" font-size="20" font-weight="600">{escape(section["title"])}</text>')
    counts = status_counts(section)
    total = sum(counts.values())
    a(f'<text x="16" y="50" fill="{MUTED}" font-size="12">{total} components · statuses written by hand, checked '
      f'against cited evidence · evidence commit {escape(inv["evidence_commit"])}</text>')
    # legend with counts
    lx, ly = 16, 64
    for s in STATUSES:
        fill, fg, code, label = STATUS_STYLE[s]
        item = f"{label} {counts[s]}"
        wtxt = text_width(item, 11) + 22
        if lx + wtxt > width - 16:
            lx, ly = 16, ly + 20
        a(f'<rect x="{lx}" y="{ly}" width="12" height="12" rx="2" fill="{fill}" stroke="{BORDER}"/>')
        a(f'<text x="{lx + 17}" y="{ly + 10}" fill="{TEXT}" font-size="11">{escape(item)}</text>')
        lx += wtxt + 10
    # measured badges (only numbers with a numerator, denominator and source)
    badges = []
    if section["id"] == "hardware":
        badges.append(("ps2autotests lines", f'{hw["lines_match"]}/{hw["lines"]}', pct(hw["lines_match"], hw["lines"])))
        badges.append(("ps2autotests programs", f'{hw["programs_pass"]}/{hw["programs"]}', pct(hw["programs_pass"], hw["programs"])))
        for c, m in inv["measurements"]["isa_coverage"]["classes"].items():
            badges.append((f'{ISA_CLASS_TITLES[c].split(" (")[0]} ISA hw-confirmed', f'{m["numerator"]}/{m["denominator"]}',
                           pct(m["numerator"], m["denominator"])))
    bx, by = 16, ly + 24
    for label, frac, p in badges:
        t1, t2 = label, f"{frac} · {p}"
        w1, w2 = text_width(t1, 10) + 12, text_width(t2, 10) + 12
        if bx + w1 + w2 > width - 16:
            bx, by = 16, by + 22
        a(f'<rect x="{_r(bx)}" y="{by}" width="{_r(w1)}" height="18" fill="{BORDER}"/>')
        a(f'<text x="{_r(bx + 6)}" y="{by + 13}" fill="{TEXT}" font-size="10">{escape(t1)}</text>')
        a(f'<rect x="{_r(bx + w1)}" y="{by}" width="{_r(w2)}" height="18" fill="#1f6feb"/>')
        a(f'<text x="{_r(bx + w1 + 6)}" y="{by + 13}" fill="#ffffff" font-size="10">{escape(t2)}</text>')
        bx += w1 + w2 + 8
    top = (by + 30) if badges else (ly + 28)
    if section.get("note"):
        a(f'<text x="16" y="{top - 4}" fill="{MUTED}" font-size="11">{escape(section["note"])}</text>')
        top += 10
    # treemap
    area = (16, top, width - 32, height - top - 16)
    groups = section["children"]
    weights = [_weight(g) for g in groups]
    for g, (gx, gy, gw, gh) in zip(groups, squarify(weights, *area)):
        _render_group(a, g, gx, gy, gw, gh, depth=0)
    a("</svg>")
    return "\n".join(out) + "\n"


def _weight(g):
    """Area weight of a group: one unit per component plus an allowance for each header strip, so a group with a
    single component still has room for its header and one readable cell."""
    if "children" not in g:
        return 1.0
    return sum(_weight(k) for k in g["children"]) + 0.7


def _render_group(a, g, x, y, w, h, depth):
    gap = 2
    x, y, w, h = x + gap / 2, y + gap / 2, w - gap, h - gap
    head = 20 if depth == 0 else 16
    a(f'<rect x="{_r(x)}" y="{_r(y)}" width="{_r(w)}" height="{_r(h)}" fill="{PANEL if depth == 0 else BG}" '
      f'stroke="{BORDER}" stroke-width="1"/>')
    c = status_counts(g)
    n = sum(c.values())
    title = (f'{g.get("category", "")} · ' if depth == 0 and g.get("category") else "") + g["title"]
    size = 12 if depth == 0 else 10
    stat = f'{n} · {c["VERIFIED_COMPLETE"]} ok · {c["VERIFIED_PARTIAL"]} part'
    label = title.upper() if depth == 0 else title
    for cand in (f"{label}  ({stat})", label, g.get("short", label)):
        if text_width(cand, size) <= w - 10:
            label = cand
            break
    else:
        raise LayoutError(f"group title {g['id']} does not fit width {w:.0f}")
    a(f'<text x="{_r(x + 5)}" y="{_r(y + head - 6)}" fill="{TEXT if depth == 0 else MUTED}" font-size="{size}" '
      f'font-weight="{600 if depth == 0 else 500}">{escape(label)}</text>')
    inner = (x + 2, y + head, w - 4, h - head - 2)
    kids = g["children"]
    if "children" in kids[0]:
        weights = [_weight(k) for k in kids]
        for k, r in zip(kids, squarify(weights, *inner)):
            _render_group(a, k, *r, depth=depth + 1)
    else:
        for leaf, (lx, ly, lw, lh) in zip(kids, squarify([1] * len(kids), *inner)):
            _render_leaf(a, leaf, lx, ly, lw, lh)


def _render_leaf(a, leaf, x, y, w, h):
    gap = 1
    x, y, w, h = x + gap, y + gap, w - 2 * gap, h - 2 * gap
    fill, fg, code, _ = STATUS_STYLE[leaf["status"]]
    size, lines = fit_label(leaf, w, h)
    dash = ' stroke-dasharray="3 2"' if leaf["status"] == "UNKNOWN" else ""
    a(f'<g><title>{escape(_title(leaf))}</title>')
    a(f'<rect x="{_r(x)}" y="{_r(y)}" width="{_r(w)}" height="{_r(h)}" fill="{fill}" stroke="{BG}" '
      f'stroke-width="1"{dash}/>')
    line_h = size + 2
    ty = y + 4 + size
    for ln in lines:
        a(f'<text x="{_r(x + 4)}" y="{_r(ty)}" fill="{fg}" font-size="{size}">{escape(ln)}</text>')
        ty += line_h
    # status code in the bottom-right corner when there is room under the label
    cw = text_width(code, 8)
    if ty - line_h + 4 + 10 <= y + h - 2 and cw + 8 <= w:
        a(f'<text x="{_r(x + w - 4)}" y="{_r(y + h - 4)}" fill="{fg}" font-size="8" text-anchor="end" '
          f'opacity="0.8">{code}</text>')
    a("</g>")


