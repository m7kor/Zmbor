#!/usr/bin/env python3
"""Design discriminating hardware probes for unresolved arithmetic models (docs/architecture/hardware-probes.md).

For each question it searches operand pairs on which the candidate models disagree, keeps a small set that separates
every pair of models (greedy set cover), and writes:
  <out>/<probe>.predictions.csv   operands and every model's predicted result (category D: model output, NOT hardware)
  <out>/<probe>.cpp               a ps2autotests-style program that prints the real results (needs ps2sdk to build;
                                   not built or run here)

usage: make_probes.py <out_dir>
"""
import itertools
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import ee_fpu_models as em  # noqa: E402
import mul_models as mm  # noqa: E402


def separating_set(models, candidates, limit):
    """Greedy: pick pairs until every pair of models that can be told apart is told apart."""
    unresolved = {(p, q) for p, q in itertools.combinations(models, 2)}
    chosen = []
    for _ in range(limit):
        best, best_gain = None, 0
        for c in candidates:
            preds = c[1]
            gain = sum(1 for p, q in unresolved if preds[p] != preds[q])
            if gain > best_gain:
                best, best_gain = c, gain
        if not best:
            break
        chosen.append(best)
        unresolved = {(p, q) for p, q in unresolved if best[1][p] == best[1][q]}
        if not unresolved:
            break
    return chosen, unresolved


def ee_add_candidates(rng):
    models = {'M1 exact toward zero': em.add_exact_toward_zero}
    for g in (0, 1, 2, 3, 8, 29):
        models[f'M2 g={g}'] = (lambda g: lambda a, b: em.add_aligned(a, b, g))(g)
    out = []
    for gap in list(range(1, 32)) + [40, 53, 54, 60]:
        for _ in range(60):
            ea = 100 + rng.randrange(40)
            a = (ea << 23) | rng.getrandbits(23)
            b = 0x80000000 | ((ea - gap) << 23) | rng.getrandbits(23) | 1   # opposite sign, low bit set
            out.append(((a, b), {n: f(a, b) for n, f in models.items()}))
    return list(models), out


def ee_mul_candidates(rng):
    models = mm.EE_MUL_MODELS
    out = []
    patterns = [0x800000, 0x800002, 0x800008, 0x800020, 0x800080, 0x800200, 0x802000, 0x820000]
    for pa in patterns:
        for _ in range(40):
            pb = 0x800000 | rng.getrandbits(23)
            a = (127 << 23) | (pa & 0x7FFFFF)
            b = (127 << 23) | (pb & 0x7FFFFF)
            out.append(((a, b), {m: mm.mul(a, b, m) for m in models}))
    for _ in range(2000):
        a = (127 << 23) | (rng.getrandbits(23) & ~((1 << rng.randrange(23)) - 1))
        b = (127 << 23) | rng.getrandbits(23)
        out.append(((a, b), {m: mm.mul(a, b, m) for m in models}))
    return models, out


def vu_mul_candidates(rng):
    # Is the VU multiplier asymmetric like the EE one? 'exact' is the current VU contract (M1), 'hot' the EE form.
    models = ['exact', 'hot']
    out = []
    for _ in range(400):
        a = (127 << 23)
        b = (127 << 23) | rng.getrandbits(23) | 2
        out.append(((a, b), {m: mm.mul(a, b, m) for m in models}))
        out.append(((b, a), {m: mm.mul(b, a, m) for m in models}))
    return models, out


PROGRAM = '''// Hardware probe: {title}
// Generated by tools/semantics/make_probes.py. Build with ps2sdk inside ps2autotests (tests/cpu/...); NOT built or
// run by Zmbor. Prints one line per operand pair: "<fs> <ft> <result>" in hex.
#include <common-ee.h>

static const u32 kPairs[][2] = {{
{pairs}
}};

int main(int argc, char *argv[]) {{
	printf("-- TEST BEGIN\\n");
	for (u32 i = 0; i < sizeof(kPairs) / sizeof(kPairs[0]); ++i) {{
		u32 r;
		asm volatile (
			"mtc1 %1, $f1\\n"
			"mtc1 %2, $f2\\n"
			"{insn}\\n"
			"mfc1 %0, $f0\\n"
			: "=r"(r) : "r"(kPairs[i][0]), "r"(kPairs[i][1]) : "memory");
		printf("%08x %08x %08x\\n", kPairs[i][0], kPairs[i][1], r);
	}}
	printf("-- TEST END\\n");
	return 0;
}}
'''

VU_PROGRAM = '''// Hardware probe: {title}
// Generated by tools/semantics/make_probes.py. Build with ps2sdk inside ps2autotests (tests/cpu/vu0_macro); NOT
// built or run by Zmbor. VU0 macro VMUL.x: prints "<fs> <ft> <result>" in hex.
#include <common-ee.h>

static const u32 kPairs[][2] = {{
{pairs}
}};

int main(int argc, char *argv[]) {{
	printf("-- TEST BEGIN\\n");
	for (u32 i = 0; i < sizeof(kPairs) / sizeof(kPairs[0]); ++i) {{
		u32 r;
		asm volatile (
			"qmtc2 %1, $vf1\\n"
			"qmtc2 %2, $vf2\\n"
			"vmul.x $vf3, $vf1, $vf2\\n"
			"qmfc2 %0, $vf3\\n"
			: "=r"(r) : "r"(kPairs[i][0]), "r"(kPairs[i][1]) : "memory");
		printf("%08x %08x %08x\\n", kPairs[i][0], kPairs[i][1], r);
	}}
	printf("-- TEST END\\n");
	return 0;
}}
'''


def write(out, name, title, models, chosen, unresolved, insn=None, vu=False):
    with open(out / f'{name}.predictions.csv', 'w', encoding='utf-8') as f:
        f.write('# category D: model predictions, not hardware results\n')
        f.write('fs,ft,' + ','.join(models) + '\n')
        for (a, b), preds in chosen:
            f.write(f'{a:08x},{b:08x},' + ','.join(f'{preds[m]:08x}' for m in models) + '\n')
    pairs = ',\n'.join(f'\t{{0x{a:08X}, 0x{b:08X}}}' for (a, b), _ in chosen)
    text = (VU_PROGRAM if vu else PROGRAM).format(title=title, pairs=pairs, insn=insn)
    (out / f'{name}.cpp').write_text(text, encoding='utf-8')
    status = 'every model pair separated' if not unresolved else f'{len(unresolved)} model pairs NOT separable here'
    print(f'{name}: {len(chosen)} probes, {status}')


if __name__ == '__main__':
    out = pathlib.Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261025)
    models, cands = ee_add_candidates(rng)
    chosen, unresolved = separating_set(models, cands, 24)
    write(out, 'p1_ee_add_guard_bits', 'EE ADD.S guard bits / sticky (evidence register 1.2)', models, chosen,
          unresolved, insn='add.s $f0, $f1, $f2')
    models, cands = ee_mul_candidates(rng)
    chosen, unresolved = separating_set(models, cands, 24)
    write(out, 'p2_ee_mul_partial_products', 'EE MUL.S partial-product truncation (evidence register 1.3)', models,
          chosen, unresolved, insn='mul.s $f0, $f1, $f2')
    models, cands = vu_mul_candidates(rng)
    chosen, unresolved = separating_set(models, cands, 8)
    write(out, 'p4_vu_mul_asymmetry', 'VU0 FMAC MUL operand-order asymmetry (evidence register 2.3)', models,
          chosen, unresolved, vu=True)
