# Opcode-table entries that select another table or a coprocessor rather than naming an instruction.
_GROUP_ENTRIES = {"OPCODE_SPECIAL", "OPCODE_REGIMM", "OPCODE_COP0", "OPCODE_COP1", "OPCODE_COP2", "OPCODE_COP3",
                  "OPCODE_MMI", "MMI_MMI0", "MMI_MMI1", "MMI_MMI2", "MMI_MMI3", "MMI_PMFHL", "MMI_PMTHL"}
_COP1_OPCODES = {"OPCODE_LWC1", "OPCODE_SWC1", "OPCODE_LDC1", "OPCODE_SDC1"}
_COP2_OPCODES = {"OPCODE_LQC2", "OPCODE_SQC2", "OPCODE_LWC2", "OPCODE_SWC2"}
# Which instruction classes the tokens of a ps2autotests directory can name.
_DIR_CLASSES = {"cpu/ee": ("ee_core", "mmi"), "cpu/ee_simd": ("mmi", "ee_core"), "cpu/ee_fpu": ("cop1",),
                "cpu/vu0_macro": ("cop2_macro",)}
# Output labels that name an instruction differently from its mnemonic. Each entry is checked against the test
# source: cpu/ee_simd/funnel.cpp prints its QFSRV section as "qdsrv" (do_qdsrv_i executes qfsrv).
_TOKEN_ALIASES = {"qdsrv": "qfsrv"}
ISA_CLASS_TITLES = {"ee_core": "EE core (R5900 base ISA)", "mmi": "EE MMI (128-bit SIMD)",
                    "cop1": "EE COP1 (FPU)", "cop2_macro": "VU0 macro mode (COP2)"}


def _enums(text):
    """enum name -> entry names; entries defined as another entry (OPCODE_LQC2 = OPCODE_LDC2) replace it, because
    the alias is the name the EE gives that encoding."""
    out = {}
    for m in re.finditer(r"enum\s+(\w+)[^{;]*\{(.*?)\};", text, re.S):
        body = re.sub(r"//[^\n]*", "", m.group(2))
        names = [name for name, _ in re.findall(r"(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", body)]
        for alias, target in re.findall(r"(\w+)\s*=\s*([A-Za-z_]\w*)\s*[,}\n]", body + "\n"):
            if target in names:
                names[names.index(target)] = alias
        out[m.group(1)] = names
    return out


def _cop1_name(entry):
    f = entry[len("COP1_S_"):]
    if f.startswith("C_"):
        return "c." + f[2:].lower()
    if f.startswith("CVT_"):
        return "cvt." + f[4:].lower() + ".s"
    if "_" in f:  # ROUND_W, TRUNC_L, ...
        return f.lower().replace("_", ".") + ".s"
    return f.lower()


def decoded_isa(instructions_h=INSTRUCTIONS_H):
    """Mnemonics the recompiler's decode tables name, per class. The tables may include encodings the EE does not
    implement (MIPS heritage); those can only lower a coverage percentage, never raise it."""
    e = _enums(instructions_h.read_text(encoding="utf-8"))
    core, mmi, cop1, cop2 = set(), set(), set(), set()
    for name in e["MipsOpcodes"]:
        if name in _GROUP_ENTRIES:
            continue
        mnemonic = name[len("OPCODE_"):].lower()
        (cop1 if name in _COP1_OPCODES else cop2 if name in _COP2_OPCODES else core).add(mnemonic)
    core.update(n[len("SPECIAL_"):].lower() for n in e["SpecialFunctions"])
    core.update(n[len("REGIMM_"):].lower() for n in e["RegimmFunctions"])
    for enum in ("MMIFunctions", "MMI0Functions", "MMI1Functions", "MMI2Functions", "MMI3Functions"):
        for n in e[enum]:
            if n not in _GROUP_ENTRIES:
                mmi.add(n.split("_", 1)[1].lower())
    for n in e["PMFHLFunctions"]:
        mmi.add("pmfhl." + n.split("_", 1)[1].lower())
    mmi.add("pmthl.lw")  # PMTHL has one defined form, LW (the sa-field table is shared with PMFHL)
    cop1.update(_cop1_name(n) for n in e["Cop1FunctionsS"])
    if "COP1_W_CVT_S" in e["Cop1FunctionsW"]:
        cop1.add("cvt.s.w")
    cop1.update({"MF": "mfc1", "CF": "cfc1", "MT": "mtc1", "CT": "ctc1"}[n[len("COP1_"):]]
                for n in e["Cop1Format"] if n[len("COP1_"):] in ("MF", "CF", "MT", "CT"))
    cop1.update("bc1" + n[len("COP1_BC_BC"):].lower() for n in e["Cop1BranchCondition"])
    for enum in ("VU0MacroSpecial1Functions", "VU0MacroSpecial2Functions"):
        cop2.update(n.split("_", 2)[2].lower() for n in e[enum])
    cop2.update(n[len("COP2_"):].lower() for n in e["Cop2Format"] if n[len("COP2_"):] in ("QMFC2", "CFC2", "QMTC2", "CTC2"))
    cop2.update("bc2" + n[len("COP2_BC_BC"):].lower() for n in e["Cop2BranchCondition"])
    return {"ee_core": sorted(core), "mmi": sorted(mmi), "cop1": sorted(cop1), "cop2_macro": sorted(cop2)}


def _tokens(expected_path):
    toks = set()
    for line in expected_path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"\s*([a-z][a-z0-9]*(?:\.[a-z0-9]+)*)\b", line)
        if m:
            toks.add(_TOKEN_ALIASES.get(m.group(1), m.group(1)))
    return toks


def measure_isa(autotests_root, hw_dashboard, isa):
    """An instruction is hardware-confirmed if a passing program names it and no mismatching program does."""
    tests = hw_dashboard["tests"]
    tests = tests.values() if isinstance(tests, dict) else tests
    passing = {c: set() for c in isa}
    failing = {c: set() for c in isa}
    for t in tests:
        elf = t["elf"]
        directory = elf.rsplit("/", 1)[0]
        classes = _DIR_CLASSES.get(directory)
        if not classes:
            continue
        expected = Path(autotests_root) / "tests" / (elf[:-len(".elf")] + ".expected")
        toks = _tokens(expected)
        if directory == "cpu/ee_fpu":
            toks = {("c." + x if x in ("f", "eq", "lt", "le") else x) for x in toks}
        for c in classes:
            hit = toks & set(isa[c])
            (passing if t["status"] == "PASS" else failing)[c].update(hit)
    out = {}
    for c in isa:
        confirmed = sorted(passing[c] - failing[c])
        in_failing = sorted(failing[c])
        out[c] = {"title": ISA_CLASS_TITLES[c], "decoded": isa[c], "confirmed": confirmed,
                  "exercised_by_mismatching_program": in_failing,
                  "not_exercised": sorted(set(isa[c]) - passing[c] - failing[c]),
                  "numerator": len(confirmed), "denominator": len(isa[c])}
    return out


def measure_hw(hw_dashboard):
    s = hw_dashboard["summary"]
    tests = hw_dashboard["tests"]
    tests = list(tests.values()) if isinstance(tests, dict) else tests
    by_area = {}
    for t in tests:
        a = by_area.setdefault(t["subsystem"], {"programs_pass": 0, "programs": 0, "lines_match": 0, "lines": 0})
        a["programs"] += 1
        a["programs_pass"] += 1 if t["status"] == "PASS" else 0
        a["lines_match"] += t["matching_lines"]
        a["lines"] += t["expected_lines"]
    return {"programs_pass": s["matching"], "programs": s["executed"], "lines_match": s["matching_lines"],
            "lines": s["expected_lines"], "crash": s["crash"], "timeout": s["timeout"],
            "by_area": {k: by_area[k] for k in sorted(by_area)},
            "tests": {t["id"]: {"status": t["status"], "lines_match": t["matching_lines"], "lines": t["expected_lines"]}
                      for t in sorted(tests, key=lambda x: x["id"])}}


