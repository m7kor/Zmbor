#!/usr/bin/env python3
"""Generate ps2xTest/src/ps2_efu_hw_vectors.inc from ps2autotests' tests/vu/lower/efu.expected.

The expected file holds results printed by a real PS2 (https://github.com/unknownbrackets/ps2autotests, ISC
license). efu.cpp loads one CVF_* constant into vf1, runs the EFU op (scalar ops on field z), WAITP, MFP vf2 and
prints vf2.x, so each row is: opcode, the four input words, the P result bits.

Usage: gen_efu_hw_vectors.py <efu.expected> <out.inc>
"""
import re
import sys

CONST = {  # efu.cpp C_* tables, words x, y, z, w
    'CVF_ZERO': [0x00000000] * 4, 'CVF_NEGZERO': [0x80000000] * 4, 'CVF_MAX': [0x7FFFFFFF] * 4,
    'CVF_MIN': [0xFFFFFFFF] * 4, 'CVF_MAX_MANTISSA': [0x3FFFFFFF] * 4, 'CVF_MAX_EXP': [0x7F800001] * 4,
    'CVF_MIN_EXP': [0x00000001] * 4, 'CVF_ONE': [0x3F800000] * 4, 'CVF_NEGONE': [0xBF800000] * 4,
    'CVF_GARBAGE1': [0x00001337] * 4, 'CVF_GARBAGE2': [0xDEADBEEF] * 4,
    'CVF_INCREASING': [0x3F800000, 0x40000000, 0x40400000, 0x40800000],
    'CVF_DECREASING': [0x40800000, 0x40400000, 0x40000000, 0x3F800000],
    'CVF_PI_OVER2': [0x3FC90FDB] * 4, 'CVF_PI': [0x40490FDB] * 4, 'CVF_3PI_OVER2': [0x4096CBE4] * 4,
}
OPCODES = {'ESADD': 0x70, 'ERSADD': 0x71, 'ELENG': 0x72, 'ERLENG': 0x73, 'EATANxy': 0x74, 'EATANxz': 0x75,
           'ESUM': 0x76, 'ESQRT': 0x78, 'ERSQRT': 0x79, 'ERCPR': 0x7A, 'ESIN': 0x7C, 'EATAN': 0x7D, 'EEXP': 0x7E}
ROW = re.compile(r'^\s+(\w+) (CVF_\w+): ([0-9a-f]{8})/')


def main():
    out = ['// Generated by ps2xTest/tools/gen_efu_hw_vectors.py from ps2autotests tests/vu/lower/efu.expected',
           '// (results printed by a real PS2; https://github.com/unknownbrackets/ps2autotests, ISC license).',
           '// Columns: name, EFU sub-opcode, vf1 words x y z w (scalar ops read z), P result bits.']
    for line in open(sys.argv[1], encoding='utf-8'):
        m = ROW.match(line)
        if not m or m.group(1) not in OPCODES:
            continue
        words = ', '.join(f'0x{w:08X}u' for w in CONST[m.group(2)])
        out.append(f'{{"{m.group(1)} {m.group(2)}", 0x{OPCODES[m.group(1)]:02X}u, {{{words}}}, 0x{int(m.group(3), 16):08X}u}},')
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'{len(out) - 3} EFU vectors')


if __name__ == '__main__':
    main()
