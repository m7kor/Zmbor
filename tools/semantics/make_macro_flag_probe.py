#!/usr/bin/env python3
"""Probe P5: does VU0 macro mode update MAC/STATUS, and when? (evidence register 2.4; docs/architecture/vu0-macro-state.md)

Competing models (none is supported by a hardware row today):
  A immediate : a macro FMAC op updates MAC and STATUS (Z/S/U/O current + sticky) as micro mode does, visible to the
                next CFC2
  B unchanged : macro FMAC ops do not touch MAC/STATUS (Zmbor today)
  C delayed   : updated as in A but only after the four-cycle FMAC flag latency: a CFC2 right after the op reads the old
                value, after four VNOPs the new one
The program reads MAC (vi17) and STATUS (vi16) before anything (m0, s0), right after op1, four VNOPs later, right
after op2 and four VNOPs later. op1 produces one flag kind per lane (x zero, y negative, z overflow, w underflow);
op2 produces none. Flag values follow Zmbor's micro-mode classification of the exact sum (O at 2^129, U below 2^-126
with Z, S from the sign); those thresholds are themselves provisional, so a disagreement in single bits is evidence
about them, not only about the model choice.

Writes <out>/p5_vu0_macro_flags.cpp (ps2autotests style; needs ps2sdk, not built here) and
<out>/p5_vu0_macro_flags.predictions.json (MODEL_PREDICTED; "m0"/"s0" stand for the first two observed readings).
usage: make_macro_flag_probe.py <out_dir>
"""
import json
import pathlib
import sys
from fractions import Fraction

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import vu_fmac_model as vm  # noqa: E402

LANE_BIT = [8, 4, 2, 1]  # x, y, z, w
OP1 = ([0x3F800000, 0xBF800000, 0x7FFFFFFF, 0x00C00000],   # fs
       [0xBF800000, 0x3F000000, 0x7FFFFFFF, 0x80A00000])   # ft: x 1-1=0, y -1+0.5<0, z ~2^130 overflow, w underflow
OP2 = ([0x3F800000, 0x40000000, 0x40400000, 0x40800000],
       [0x3F800000, 0x3F800000, 0x3F800000, 0x3F800000])   # all positive normal results: no flag


def flags(fs, ft):
    """(MAC, STATUS current bits) of VADD fs, ft under Zmbor's micro-mode classification."""
    mac, status = 0, 0
    for lane in range(4):
        exact = vm.value(fs[lane]) + vm.value(ft[lane])
        bit = LANE_BIT[lane]
        mag = abs(exact)
        if exact < 0:
            mac |= bit << 4
            status |= 2
        if mag == 0:
            mac |= bit
            status |= 1
        elif mag >= Fraction(2) ** 129:
            mac |= bit << 12
            status |= 8
        elif mag < Fraction(2) ** -126:
            mac |= bit | (bit << 8)
            status |= 1 | 4
    return mac, status


def readings():
    m1, c1 = flags(*OP1)
    m2, c2 = flags(*OP2)
    sticky1 = (c1 & 0xF) << 6
    names = ['before: MAC', 'before: STATUS', 'op1 now: MAC', 'op1 now: STATUS', 'op1 +4: MAC', 'op1 +4: STATUS',
             'op2 now: MAC', 'op2 now: STATUS', 'op2 +4: MAC', 'op2 +4: STATUS']
    # sticky bits accumulate on top of whatever s0 held: expressed as "s0|<bits>"
    a = ['m0', 's0', m1, f's0|{c1 | sticky1:#x}', m1, f's0|{c1 | sticky1:#x}', m2, f's0|{c2 | sticky1:#x}', m2,
         f's0|{c2 | sticky1:#x}']
    b = ['m0', 's0'] * 5
    c = ['m0', 's0', 'm0', 's0', m1, f's0|{c1 | sticky1:#x}', m1, f's0|{c1 | sticky1:#x}', m2, f's0|{c2 | sticky1:#x}']
    return names, {'A immediate': a, 'B unchanged': b, 'C delayed': c}


PROGRAM = '''// Hardware probe P5: VU0 macro-mode MAC/STATUS after VADD (evidence register 2.4)
// Generated by tools/semantics/make_macro_flag_probe.py. Build with ps2sdk inside ps2autotests (tests/cpu/vu0_macro);
// NOT built or run by Zmbor. Prints one hex value per line, in the order of the predictions file.
#include <common-ee.h>

static const u32 __attribute__((aligned(16))) kOp1Fs[4] = {{{op1fs}}};
static const u32 __attribute__((aligned(16))) kOp1Ft[4] = {{{op1ft}}};
static const u32 __attribute__((aligned(16))) kOp2Fs[4] = {{{op2fs}}};
static const u32 __attribute__((aligned(16))) kOp2Ft[4] = {{{op2ft}}};

int main(int argc, char *argv[]) {{
	u32 r[10];
	printf("-- TEST BEGIN\\n");
	asm volatile (
		"lqc2 $vf1, 0(%10)\\n"
		"lqc2 $vf2, 0(%11)\\n"
		"lqc2 $vf4, 0(%12)\\n"
		"lqc2 $vf5, 0(%13)\\n"
		"cfc2 %0, $vi17\\n"
		"cfc2 %1, $vi16\\n"
		"vadd.xyzw $vf3, $vf1, $vf2\\n"
		"cfc2 %2, $vi17\\n"
		"cfc2 %3, $vi16\\n"
		"vnop\\n vnop\\n vnop\\n vnop\\n"
		"cfc2 %4, $vi17\\n"
		"cfc2 %5, $vi16\\n"
		"vadd.xyzw $vf6, $vf4, $vf5\\n"
		"cfc2 %6, $vi17\\n"
		"cfc2 %7, $vi16\\n"
		"vnop\\n vnop\\n vnop\\n vnop\\n"
		"cfc2 %8, $vi17\\n"
		"cfc2 %9, $vi16\\n"
		: "=r"(r[0]), "=r"(r[1]), "=r"(r[2]), "=r"(r[3]), "=r"(r[4]), "=r"(r[5]), "=r"(r[6]), "=r"(r[7]),
		  "=r"(r[8]), "=r"(r[9])
		: "r"(kOp1Fs), "r"(kOp1Ft), "r"(kOp2Fs), "r"(kOp2Ft)
		: "memory");
	for (int i = 0; i < 10; ++i)
		printf("%08x\\n", r[i]);
	printf("-- TEST END\\n");
	return 0;
}}
'''


if __name__ == '__main__':
    out = pathlib.Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    names, models = readings()
    hexs = lambda v: ', '.join(f'0x{x:08X}' for x in v)
    (out / 'p5_vu0_macro_flags.cpp').write_text(
        PROGRAM.format(op1fs=hexs(OP1[0]), op1ft=hexs(OP1[1]), op2fs=hexs(OP2[0]), op2ft=hexs(OP2[1])), encoding='utf-8')
    pred = {'probe': 'p5_vu0_macro_flags', 'evidence_class': 'MODEL_PREDICTED',
            'note': 'm0/s0 = the first two observed readings; "s0|0x..." = s0 with those bits set',
            'readings': names, 'models': {k: [v if isinstance(v, str) else f'{v:#010x}' for v in vals]
                                          for k, vals in models.items()}}
    (out / 'p5_vu0_macro_flags.predictions.json').write_text(json.dumps(pred, indent=1) + '\n', encoding='utf-8')
    distinct = len({tuple(v) for v in pred['models'].values()})
    print(f'p5_vu0_macro_flags: {len(names)} readings, {len(models)} models, {distinct} distinct prediction sequences')
