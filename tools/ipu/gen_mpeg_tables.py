"""Extracts the ISO/IEC 13818-2 table values (B-9, B-12, B-13, B-14, B-15) from DobieStation's table data and writes them
in this project's own format (code, length, run, level / size), then checks each table is prefix-free.

The table values are facts of the standard; the reference sources are read, not copied, and are not part of this
repository (DobieStation src/core/ee/ipu: lumtable, chromtable, codedblockpattern, dct_coeff_table0/1).

usage: gen_mpeg_tables.py <refs dir> <out header>
"""
import re
import sys
from pathlib import Path

refs, out = Path(sys.argv[1]), Path(sys.argv[2])


def entries(text, name):
    block = text[text.index(name):]
    block = block[block.index('{') + 1:block.index('};')]
    return [tuple(int(v, 0) for v in m.groups()) for m in re.finditer(r'\{\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(-?\w+)\s*,\s*(\d+)\s*\}', block)
            if m.group(2).lstrip('-').isdigit()]


def runlevels(text, name):
    block = text[text.index(name):]
    block = block[block.index('{') + 1:block.index('};')]
    pairs = []
    for m in re.finditer(r'\{\s*(RUN_ESCAPE|\d+)\s*,\s*(\d+)\s*\}', block):
        pairs.append((-1 if m.group(1) == 'RUN_ESCAPE' else int(m.group(1)), int(m.group(2))))
    return pairs


def prefix_free(codes):
    words = [format(c, '0%db' % n) for c, n in codes]
    for i, a in enumerate(words):
        for j, b in enumerate(words):
            if i != j and b.startswith(a):
                raise SystemExit(f'not prefix-free: {a} is a prefix of {b}')


lines = ['// Generated by gen_mpeg_tables.py from the values of ISO/IEC 13818-2 tables B-9 and B-12 to B-15. Do not edit.',
         '#pragma once', '', '#include <cstdint>', '', 'namespace ps2_ipu_tables', '{',
         '    // B-9 value: coded_block_pattern; B-12/B-13 value: dct_dc_size.',
         '    struct CodeValue { uint16_t code; uint8_t length; uint8_t value; };',
         '    // run -1: escape (6-bit run and 12-bit signed level follow, MPEG-1: 8/16-bit level)',
         '    struct DctCode { uint16_t code; uint8_t length; int8_t run; uint8_t level; };', '']

for name, fname in (('kCodedBlockPattern', 'codedblockpattern.cpp'), ('kDcLuminance', 'lumtable.cpp'), ('kDcChrominance', 'chromtable.cpp')):
    text = (refs / f'dobie_{fname}').read_text()
    rows = entries(text, '[] =')
    prefix_free([(k, b) for k, _, b in rows])
    lines.append(f'    constexpr CodeValue {name}[] = {{')
    lines += [f'        {{0x{k:X}, {b}, {v}}},' for k, v, b in rows]
    lines.append('    };')

for name, fname, cls, eob in (('kDctTableB14', 'dct_coeff_table0.cpp', 'DCT_Coeff_Table0', (0b10, 2)),
                              ('kDctTableB15', 'dct_coeff_table1.cpp', 'DCT_Coeff_Table1', (0b0110, 4))):
    text = (refs / f'dobie_{fname}').read_text()
    rows = entries(text, f'{cls}::table[]')
    pairs = runlevels(text, f'{cls}::runlevel_table[]')
    out_rows = []
    for key, index, bits in rows:
        run, level = pairs[index]
        # The sign bit follows every code except escape; codes are stored without it.
        out_rows.append((key, bits, run, level))
    prefix_free([(k, b) if r == -1 else (k << 1, b + 1) for k, b, r, _ in out_rows] + [eob])
    lines.append(f'    // {len(out_rows)} codes; EOB is {format(eob[0], "0%db" % eob[1])}; codes are stored without their sign bit.')
    lines.append(f'    constexpr DctCode {name}[] = {{')
    lines += [f'        {{0x{k:X}, {b}, {r}, {lv}}},' for k, b, r, lv in out_rows]
    lines.append('    };')
lines += ['}', '']
out.write_text('\n'.join(lines), encoding='utf-8')
print('wrote', out)
