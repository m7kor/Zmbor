#!/usr/bin/env python3
"""Generate ps2xTest/src/ps2_simd_hw_vectors.inc and ps2_pdiv_hw_vectors.inc from ps2autotests' tests/cpu/ee_simd
{shuffle,arithmetic,logic,muldiv}.expected.

The expected files hold results printed by a real PS2 (https://github.com/unknownbrackets/ps2autotests, ISC
license). Only rows whose operands are named shared.h constants are used ("  pexch C_P_S8_A: w3 w2 w1 w0"), since
their 128-bit inputs are exactly known. The tests print "OP rd, A, B" with A and B in assembler order, so A is rs
(rt for the one-operand forms and the value shifted by PSLLVW/PSRLVW/PSRAVW) and B is rt (rs, the shift amounts).

The PDIVW/PDIVUW/PDIVBW rows ("  pdivbw 53, 2: H: <hi> <hi1> L: <lo> <lo1>") use muldiv.cpp's SET_U32 inputs: lui/ori
sign-extends the immediate and pcpyld copies that doubleword to both halves.

Usage: gen_simd_hw_vectors.py <ps2autotests>/tests/cpu/ee_simd <out dir>
"""
import pathlib
import re
import sys

UNARY = ('pexch', 'pexcw', 'pexeh', 'pexew', 'prevh', 'prot3w', 'pabsh', 'pabsw')
BINARY = ('pinth', 'pinteh', 'padduh', 'psubuh', 'psllvw', 'psrlvw', 'psravw')
FILES = ('shuffle.expected', 'arithmetic.expected', 'logic.expected')

CONST = {  # tests/cpu/ee_simd/shared.h, words low to high
    'C_ZERO': [0, 0, 0, 0], 'C_ONE': [1, 0, 0, 0], 'C_NEGONE': [0xFFFFFFFF] * 4,
    'C_S16_MAX': [0x7FFF, 0, 0, 0], 'C_S16_MIN': [0xFFFF8000, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF],
    'C_S32_MAX': [0x7FFFFFFF, 0, 0, 0], 'C_S32_MIN': [0x80000000, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF],
    'C_S64_MAX': [0xFFFFFFFF, 0x7FFFFFFF, 0, 0], 'C_S64_MIN': [0, 0x80000000, 0xFFFFFFFF, 0xFFFFFFFF],
    'C_GARBAGE1': [0x1337, 0x1338, 0x1339, 0x133A], 'C_GARBAGE2': [0xDEADBEEF, 0xDEADBEEE, 0xDEADBEED, 0xDEADBEEC],
    'C_P_S8_A': [0x80808080, 0xFFFFFFFF, 0x12345678, 0x7F7F7F7F], 'C_P_S8_B': [0x80FF127F, 0xFF807F34, 0x567F80FF, 0x7F78FF80],
    'C_P_S16_A': [0x80008000, 0xFFFFFFFF, 0x12345678, 0x7FFF7FFF], 'C_P_S16_B': [0x8000FFFF, 0x12347FFF, 0xFFFF8000, 0x7FFF5678],
    'C_P_S32_A': [0x80000000, 0xFFFFFFFF, 0x12345678, 0x7FFFFFFF], 'C_P_S32_B': [0xFFFFFFFF, 0x80000000, 0x7FFFFFFF, 0x12345678],
    'C_P_S32_C': [0x80000000, 0xFFFFFFFF, 0x12345678, 0x7FFFFFFF], 'C_P_S32_D': [0x7FFFFFFF, 0x12345678, 0xFFFFFFFF, 0x80000000],
    'C_P_S32_E': [0x00000000, 0x7FFFFFFF, 0xFFFFFFFF, 0x80000000], 'C_P_S32_F': [0xFFFFFFFF, 0x80000000, 0x00000000, 0x7FFFFFFF],
}
DIV_LINE = re.compile(r'^\s+(pdivw|pdivuw|pdivbw) (-?\d+), (-?\d+): H: ([0-9a-f]{16}) ([0-9a-f]{16}) '
                      r'L: ([0-9a-f]{16}) ([0-9a-f]{16})$')
LINE = re.compile(r'^\s+(\w+) (C_\w+)(?:, (C_\w+))?: ([0-9a-f]{8}) ([0-9a-f]{8}) ([0-9a-f]{8}) ([0-9a-f]{8})$')


def words(v):
    return '{' + ', '.join(f'0x{w:08X}u' for w in v) + '}'


def main():
    src, out_dir = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    out = ['// Generated by ps2xTest/tools/gen_simd_hw_vectors.py from ps2autotests tests/cpu/ee_simd/{shuffle,arithmetic,logic}',
           '// .expected (results printed by a real PS2; https://github.com/unknownbrackets/ps2autotests, ISC license).',
           '// Columns: op, A, B, result; words low to high. A/B are the operands in assembler order (see the generator).']
    counts = {}
    for name in FILES:
        for line in (src / name).read_text(encoding='utf-8').splitlines():
            m = LINE.match(line)
            if not m or m.group(1) not in UNARY + BINARY or m.group(2) not in CONST:
                continue
            op, a, b = m.group(1), m.group(2), m.group(3)
            if (op in BINARY) != (b is not None) or (b is not None and b not in CONST):
                continue
            result = [int(m.group(i), 16) for i in (7, 6, 5, 4)]
            out.append(f'{{"{op}", {words(CONST[a])}, {words(CONST[b] if b else [0] * 4)}, {words(result)}}}, '
                       f'// {a}{", " + b if b else ""}')
            counts[op] = counts.get(op, 0) + 1
    missing = [op for op in UNARY + BINARY if op not in counts]
    if missing:
        raise SystemExit(f'no rows for {missing}')
    (out_dir / 'ps2_simd_hw_vectors.inc').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'{sum(counts.values())} vectors: {counts}')

    def set_u32(text):
        v = int(text) & 0xFFFFFFFF
        high = 0xFFFFFFFF if v & 0x80000000 else 0
        return [v, high, v, high]

    div = ['// Generated by ps2xTest/tools/gen_simd_hw_vectors.py from ps2autotests tests/cpu/ee_simd/muldiv.expected',
           '// (results printed by a real PS2; https://github.com/unknownbrackets/ps2autotests, ISC license).',
           '// Columns: op, rs, rt (words low to high), HI, HI1, LO, LO1.']
    for line in (src / 'muldiv.expected').read_text(encoding='utf-8').splitlines():
        m = DIV_LINE.match(line)
        if m:
            hi, hi1, lo, lo1 = (int(m.group(i), 16) for i in (4, 5, 6, 7))
            div.append(f'{{"{m.group(1)}", {words(set_u32(m.group(2)))}, {words(set_u32(m.group(3)))}, '
                       f'0x{hi:016X}ull, 0x{hi1:016X}ull, 0x{lo:016X}ull, 0x{lo1:016X}ull}}, // {m.group(2)}, {m.group(3)}')
    (out_dir / 'ps2_pdiv_hw_vectors.inc').write_text('\n'.join(div) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(div) - 3} divide vectors')


if __name__ == '__main__':
    main()
